CREATE OR REPLACE FUNCTION public.create_online_order(
    p_outlet_id UUID,
    p_customer_name TEXT,
    p_customer_phone VARCHAR(30),
    p_service_type VARCHAR(20),
    p_delivery_address TEXT,
    p_payment_method VARCHAR(30),
    p_notes TEXT,
    p_items JSONB, -- Array of { product_id, variant_id, addon_ids: [], quantity, item_notes }
    p_raw_tracking_token TEXT, -- 256-bit cryptographically secure token generated by client
    p_token_hash TEXT -- SHA-256 hash of the tracking token to be stored
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
    v_order_id UUID := gen_random_uuid();
    v_order_number VARCHAR(50);
    v_subtotal NUMERIC(12,2) := 0.00;
    v_tax_rate NUMERIC(5,2) := 10.00;
    v_tax_amount NUMERIC(12,2) := 0.00;
    v_service_rate NUMERIC(5,2) := 0.00;
    v_service_amount NUMERIC(12,2) := 0.00;
    v_delivery_fee NUMERIC(12,2) := 0.00;
    v_grand_total NUMERIC(12,2) := 0.00;
    v_item RECORD;
    v_product RECORD;
    v_variant RECORD;
    v_addon RECORD;
    v_unit_price NUMERIC(12,2);
    v_line_total NUMERIC(12,2);
    v_addons_snapshot JSONB;
    v_today_code TEXT;
    v_daily_seq INTEGER;
    v_customer_id UUID;
    v_payment_status VARCHAR(30);
BEGIN
    -- 1. Basic validation
    IF p_customer_name IS NULL OR trim(p_customer_name) = '' THEN
        RAISE EXCEPTION 'Nama pelanggan tidak boleh kosong.';
    END IF;

    IF p_customer_phone IS NULL OR trim(p_customer_phone) = '' THEN
        RAISE EXCEPTION 'Nomor telepon pelanggan tidak boleh kosong.';
    END IF;

    IF jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Keranjang pesanan tidak boleh kosong.';
    END IF;

    IF p_service_type NOT IN ('DINE_IN', 'TAKEAWAY', 'DELIVERY', 'PICKUP') THEN
        RAISE EXCEPTION 'Tipe layanan tidak valid: %', p_service_type;
    END IF;

    IF p_payment_method NOT IN ('CASH', 'QRIS', 'BANK_TRANSFER', 'DEBIT_CARD', 'CREDIT_CARD') THEN
        RAISE EXCEPTION 'Metode pembayaran tidak valid: %', p_payment_method;
    END IF;

    -- 2. Delivery fee calculation
    IF p_service_type = 'DELIVERY' THEN
        v_delivery_fee := 10000.00; -- Standard flat delivery fee
        IF p_delivery_address IS NULL OR trim(p_delivery_address) = '' THEN
            RAISE EXCEPTION 'Alamat pengantaran wajib diisi untuk layanan Delivery.';
        END IF;
    END IF;

    -- 3. Fetch tax and service charge settings
    SELECT COALESCE(tax_rate_percent, 10.00) INTO v_tax_rate
    FROM public.tax_settings
    WHERE outlet_id = p_outlet_id AND is_enabled = true;

    SELECT COALESCE(service_rate_percent, 0.00) INTO v_service_rate
    FROM public.service_charge_settings
    WHERE outlet_id = p_outlet_id AND is_enabled = true;

    -- 4. Generate Order Number (e.g. ORD-YYYYMMDD-XXXX)
    v_today_code := to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYYMMDD');
    SELECT COUNT(*) + 1 INTO v_daily_seq
    FROM public.orders
    WHERE order_number LIKE 'ORD-' || v_today_code || '-%';

    v_order_number := 'ORD-' || v_today_code || '-' || lpad(v_daily_seq::text, 4, '0');

    -- 5. Upsert or find customer
    SELECT id INTO v_customer_id
    FROM public.customers
    WHERE outlet_id = p_outlet_id AND phone = p_customer_phone
    LIMIT 1;

    IF v_customer_id IS NULL THEN
        INSERT INTO public.customers (outlet_id, name, phone, address, created_at, updated_at)
        VALUES (p_outlet_id, p_customer_name, p_customer_phone, p_delivery_address, now(), now())
        RETURNING id INTO v_customer_id;
    END IF;

    -- 6. Insert base order header
    INSERT INTO public.orders (
        id, outlet_id, customer_id, order_number, channel, service_type, order_status,
        customer_name_snapshot, customer_phone_snapshot, delivery_address_snapshot,
        subtotal, discount_amount, tax_amount, service_charge_amount, delivery_fee, grand_total,
        notes, created_at, updated_at
    ) VALUES (
        v_order_id, p_outlet_id, v_customer_id, v_order_number, 'ONLINE', p_service_type, 'NEW',
        p_customer_name, p_customer_phone, p_delivery_address,
        0, 0, 0, 0, v_delivery_fee, 0,
        p_notes, now(), now()
    );

    -- 7. Process each order item with authoritative database prices and stock check
    FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(
        product_id UUID,
        variant_id UUID,
        addon_ids UUID[],
        quantity INTEGER,
        item_notes TEXT
    ) LOOP
        -- Verify product
        SELECT * INTO v_product
        FROM public.products
        WHERE id = v_item.product_id AND is_active = true AND is_available = true;

        IF v_product IS NULL THEN
            RAISE EXCEPTION 'Produk tidak ditemukan atau tidak aktif: %', v_item.product_id;
        END IF;

        IF v_item.quantity <= 0 THEN
            RAISE EXCEPTION 'Kuantitas produk % tidak valid: %', v_product.name, v_item.quantity;
        END IF;

        -- Stock check
        IF v_product.current_stock < v_item.quantity THEN
            RAISE EXCEPTION 'Stok produk % tidak mencukupi (Tersisa: %, Diminta: %)',
                v_product.name, v_product.current_stock, v_item.quantity;
        END IF;

        -- Base unit price
        v_unit_price := v_product.base_price;

        -- Variant check & adjustment
        IF v_item.variant_id IS NOT NULL THEN
            SELECT * INTO v_variant
            FROM public.product_variants
            WHERE id = v_item.variant_id AND product_id = v_item.product_id AND is_active = true;

            IF v_variant IS NOT NULL THEN
                v_unit_price := v_unit_price + v_variant.price_adjustment;
            END IF;
        END IF;

        -- Addons check & calculation
        v_addons_snapshot := '[]'::jsonb;
        IF v_item.addon_ids IS NOT NULL AND array_length(v_item.addon_ids, 1) > 0 THEN
            FOR v_addon IN
                SELECT name, price FROM public.product_addons
                WHERE id = ANY(v_item.addon_ids) AND product_id = v_item.product_id AND is_active = true
            LOOP
                v_unit_price := v_unit_price + v_addon.price;
                v_addons_snapshot := v_addons_snapshot || jsonb_build_object('name', v_addon.name, 'price', v_addon.price);
            END LOOP;
        END IF;

        v_line_total := v_unit_price * v_item.quantity;
        v_subtotal := v_subtotal + v_line_total;

        -- Insert order item snapshot
        INSERT INTO public.order_items (
            order_id, product_id, product_name_snapshot, sku_snapshot,
            variant_name_snapshot, addons_snapshot, unit_price, quantity,
            discount_amount, line_total, item_notes, created_at
        ) VALUES (
            v_order_id, v_item.product_id, v_product.name, v_product.sku,
            CASE WHEN v_variant IS NOT NULL THEN v_variant.name ELSE NULL END,
            v_addons_snapshot, v_unit_price, v_item.quantity,
            0.00, v_line_total, v_item.item_notes, now()
        );

        -- Decrement stock and record movement
        UPDATE public.products
        SET current_stock = current_stock - v_item.quantity,
            updated_at = now()
        WHERE id = v_item.product_id;

        INSERT INTO public.stock_movements (
            outlet_id, product_id, movement_type, quantity_change,
            previous_stock, new_stock, reference_id, reason, created_at
        ) VALUES (
            p_outlet_id, v_item.product_id, 'SALE', -v_item.quantity,
            v_product.current_stock, v_product.current_stock - v_item.quantity,
            v_order_number, 'Penjualan Online Checkout', now()
        );
    END LOOP;

    -- 8. Compute authoritative totals
    v_tax_amount := round(v_subtotal * (v_tax_rate / 100.0), 2);
    v_service_amount := round(v_subtotal * (v_service_rate / 100.0), 2);
    v_grand_total := v_subtotal + v_tax_amount + v_service_amount + v_delivery_fee;

    -- Update order with final calculated totals
    UPDATE public.orders
    SET subtotal = v_subtotal,
        tax_amount = v_tax_amount,
        service_charge_amount = v_service_amount,
        delivery_fee = v_delivery_fee,
        grand_total = v_grand_total,
        updated_at = now()
    WHERE id = v_order_id;

    -- 9. Insert initial status history
    INSERT INTO public.order_status_history (
        order_id, previous_status, new_status, actor_name, reason, created_at
    ) VALUES (
        v_order_id, NULL, 'NEW', 'Customer Online Checkout', 'Pesanan online berhasil dibuat', now()
    );

    -- 10. Insert Payment record
    IF p_payment_method IN ('QRIS', 'BANK_TRANSFER') THEN
        v_payment_status := 'PENDING_VERIFICATION';
    ELSE
        v_payment_status := 'UNPAID';
    END IF;

    INSERT INTO public.order_payments (
        outlet_id, order_id, payment_method, status, amount, created_at, updated_at
    ) VALUES (
        p_outlet_id, v_order_id, p_payment_method, v_payment_status, v_grand_total, now(), now()
    );

    -- 11. Save 256-bit Token Hash for secure guest tracking
    INSERT INTO public.public_order_tokens (
        order_id, token_hash, expires_at, created_at
    ) VALUES (
        v_order_id, p_token_hash, now() + interval '30 days', now()
    );

    -- 12. Return structured response with one-time plain tracking token
    RETURN jsonb_build_object(
        'success', true,
        'order_id', v_order_id,
        'order_number', v_order_number,
        'grand_total', v_grand_total,
        'subtotal', v_subtotal,
        'tax_amount', v_tax_amount,
        'delivery_fee', v_delivery_fee,
        'service_type', p_service_type,
        'payment_method', p_payment_method,
        'payment_status', v_payment_status,
        'tracking_token', p_raw_tracking_token
    );
END;
$$;

COMMENT ON FUNCTION public.create_online_order IS 'Authoritatively creates an online order, validates stock, recalculates prices, and creates payments and tracking token';
